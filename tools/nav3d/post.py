# Post-process renders into the site:  python tools/nav3d/post.py [room ...]
#  - out/<room>.png (2x) -> img/nav/<room>.png at native size, 256 colours with dithering (like a 1995 SVGA screen)
#  - out/<room>.json     -> js/nav2d/renders.js (hotspot polygons + anchor quads for every room)
import json, os, sys, glob
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "out")
IMG = os.path.join(SITE, "img", "nav")
os.makedirs(IMG, exist_ok=True)

rooms = sys.argv[1:] or sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(OUT, "*.json")))
for room in rooms:
    meta = json.load(open(os.path.join(OUT, room + ".json")))
    src = os.path.join(OUT, room + ".png")
    if not os.path.exists(src): continue
    im = Image.open(src).convert("RGB").resize((meta["W"], meta["H"]), Image.LANCZOS)
    q = im.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
    q.save(os.path.join(IMG, room + ".png"), optimize=True)
    print("img", room, os.path.getsize(os.path.join(IMG, room + ".png")) // 1024, "KB")

# every json -> one module
allr = {}
for p in sorted(glob.glob(os.path.join(OUT, "*.json"))):
    room = os.path.splitext(os.path.basename(p))[0]
    allr[room] = json.load(open(p))
js = "// Generated by tools/nav3d/post.py from the Blender scenes. Hotspot polygons (far to near) and anchor quads, in stage pixels.\n"
js += "export const RENDERS = " + json.dumps(allr, separators=(",", ":")) + ";\n"
open(os.path.join(SITE, "js", "nav2d", "renders.js"), "w").write(js)
print("renders.js", len(js) // 1024, "KB,", len(allr), "rooms")
